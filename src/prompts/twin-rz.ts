// Поскольку реальных постов Виктории в БД пока нет, голос строится на:
//   1. Принципах из knowledge/voice-analysis-ye-v3.md (общий глоссарий, запреты)
//   2. Реальных кейсах из voice_analysis.real_stories — она использует их как
//      ЗЕРКАЛО для собственной истории, не как наблюдение.
